// Writes src/location.rs from the web app's list, so the server accepts the same cities the web app offers.
// Run again after changing the list:
//   node scripts/gen_location.mjs ../../holidayfriend-web/src/constants/location.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/gen_location.mjs <path to holidayfriend-web/src/constants/location.ts>');
  process.exit(1);
}

// the file is plain data, so dropping `export` and the type annotation leaves javascript to run
const code = readFileSync(source, 'utf8').replace(
  /export const (\w+)(: [^=]+)? =/g,
  'globalThis.$1 =',
);
new Function(code)();
const { CITIES_BY_COUNTRY } = globalThis;

// sorted by code, so the lookup can binary search
const entries = Object.entries(CITIES_BY_COUNTRY).sort(([a], [b]) => (a < b ? -1 : 1));
// JSON string literals are valid rust string literals for these names: no backslashes or control characters
const rows = entries
  .map(([country, cities]) => `    ("${country}", &[${cities.map((city) => JSON.stringify(city)).join(', ')}]),`)
  .join('\n');

const rust = `// @generated by scripts/gen_location.mjs from holidayfriend-web's src/constants/location.ts, don't edit by hand

/// The cities the web app offers, by ISO 3166-1 alpha-2 country code, sorted by code.
// one country a line, and what the script writes stays as it is
#[rustfmt::skip]
static CITIES_BY_COUNTRY: &[(&str, &[&str])] = &[
${rows}
];

/// Whether it's one of the cities the web app offers, as the web app spells it.
pub fn is_city(country: &str, city: &str) -> bool {
    CITIES_BY_COUNTRY
        .binary_search_by_key(&country, |(code, _)| code)
        .is_ok_and(|index| CITIES_BY_COUNTRY[index].1.contains(&city))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn is_sorted_by_code() {
        assert!(
            CITIES_BY_COUNTRY
                .windows(2)
                .all(|pair| pair[0].0 < pair[1].0)
        );
    }

    #[test]
    fn knows_a_city_of_its_country() {
        assert!(is_city("JP", "Tokyo"));
        assert!(is_city("BR", "São Paulo"));
    }

    #[test]
    fn rejects_a_city_of_another_country() {
        assert!(!is_city("KR", "Tokyo"));
    }

    #[test]
    fn rejects_what_isnt_listed() {
        assert!(!is_city("JP", "tokyo"));
        assert!(!is_city("JP", "Atlantis"));
        assert!(!is_city("XX", "Tokyo"));
    }
}
`;

const target = fileURLToPath(new URL('../src/location.rs', import.meta.url));
writeFileSync(target, rust);
console.log(`wrote ${entries.length} countries to ${target}`);
